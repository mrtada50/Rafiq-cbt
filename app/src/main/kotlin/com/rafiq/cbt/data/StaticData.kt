fun encodeChain(steps: List<String>): String {
    val arr = JSONArray()
    steps.forEach { arr.put(it) }
    return arr.toString()
}

fun decodeChain(json: String): List<String> {
    return try {
        val arr = JSONArray(json)
        (0 until arr.length()).map { arr.getString(it) }
    } catch (e: Exception) {
        emptyList()
    }
}
